"""
DeepShield AI - Single Image Deepfake Prediction Pipeline
Loads trained ResNet-18 model checkpoint, executes face detection and cropping,
computes calibrated Softmax class probabilities, and provides structured results.
"""

import os
import sys

# Ensure repository root is in python search path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

import json
import argparse
from typing import Dict, Any, Optional
import torch

from src.utils import load_config, get_device, load_checkpoint, setup_logger
from src.model import build_model
from src.preprocessing import preprocess_image

logger = setup_logger("DeepShieldAI.PredictImage")


def predict_single_image(
    image_path: str,
    checkpoint_path: str = "models/best_model.pth",
    config_path: str = "configs/config.yaml",
    detect_face: bool = True,
    device_name: Optional[str] = None
) -> Dict[str, Any]:
    """
    Executes deepfake classification for a single image.

    Returns:
        Dictionary with predicted class, confidence, probabilities, and face detection details.
    """
    if not os.path.exists(image_path):
        raise FileNotFoundError(f"Input image file does not exist at: {image_path}")

    if not os.path.exists(checkpoint_path):
        raise FileNotFoundError(
            f"Checkpoint file '{checkpoint_path}' not found! "
            "Please train the model on Google Colab or locally before running inference."
        )

    config = load_config(config_path)
    device = get_device(device_name)

    # 1. Image Preprocessing & Face Detection
    try:
        input_tensor, meta = preprocess_image(
            image_source=image_path,
            config=config,
            detect_face=detect_face,
            is_training=False
        )
    except Exception as e:
        raise RuntimeError(f"Preprocessing error for image '{image_path}': {e}")

    # 2. Model Initialization and Checkpoint Loading
    model = build_model(config)
    model, _, _ = load_checkpoint(checkpoint_path, model, device=device)
    model.eval()

    # 3. Model Inference
    input_tensor = input_tensor.to(device)
    with torch.no_grad():
        logits = model(input_tensor)
        probs = torch.softmax(logits, dim=1).cpu().numpy()[0]

    # Index 0 is REAL, Index 1 is FAKE
    prob_real = float(probs[0])
    prob_fake = float(probs[1])

    threshold = config.get("inference", {}).get("confidence_threshold", 0.50)
    if prob_fake >= threshold:
        predicted_class = "FAKE"
        confidence = prob_fake
    else:
        predicted_class = "REAL"
        confidence = prob_real

    result = {
        "image_path": os.path.abspath(image_path),
        "predicted_class": predicted_class,
        "confidence": round(confidence, 4),
        "confidence_percent": f"{confidence * 100:.2f}%",
        "probabilities": {
            "REAL": round(prob_real, 4),
            "FAKE": round(prob_fake, 4)
        },
        "face_detected": meta["face_detected"],
        "bounding_box": meta["bounding_box"],
        "disclaimer": (
            "NOTICE: Predictions are probabilistic classifications generated by a machine learning model. "
            "They should not be used as definitive forensic authenticity verifications."
        )
    }

    return result


def main():
    parser = argparse.ArgumentParser(description="Predict whether an image is REAL or FAKE using DeepShield AI")
    parser.add_argument("--image", type=str, required=True, help="Path to input image file")
    parser.add_argument("--checkpoint", type=str, default="models/best_model.pth", help="Path to model weights (.pth)")
    parser.add_argument("--config", type=str, default="configs/config.yaml", help="Path to config.yaml")
    parser.add_argument("--no_face_detect", action="store_true", help="Disable automatic face detection and cropping")
    parser.add_argument("--device", type=str, default=None, help="Device to use ('cpu' or 'cuda')")
    parser.add_argument("--output", type=str, default=None, help="Path to save output JSON")

    args = parser.parse_args()

    try:
        res = predict_single_image(
            image_path=args.image,
            checkpoint_path=args.checkpoint,
            config_path=args.config,
            detect_face=not args.no_face_detect,
            device_name=args.device
        )

        print("\n" + "=" * 55)
        print("          DEEPSHIELD AI - IMAGE ANALYSIS RESULT          ")
        print("=" * 55)
        print(f"File:             {res['image_path']}")
        print(f"Face Detected:    {'Yes' if res['face_detected'] else 'No (analyzed full frame)'}")
        if res['bounding_box']:
            print(f"Face Bounding Box: [x={res['bounding_box'][0]}, y={res['bounding_box'][1]}, w={res['bounding_box'][2]}, h={res['bounding_box'][3]}]")
        print(f"Verdict:          {res['predicted_class']}")
        print(f"Confidence:       {res['confidence_percent']}")
        print(f"  - Prob(REAL):   {res['probabilities']['REAL'] * 100:.2f}%")
        print(f"  - Prob(FAKE):   {res['probabilities']['FAKE'] * 100:.2f}%")
        print("-" * 55)
        print(res['disclaimer'])
        print("=" * 55 + "\n")

        if args.output:
            with open(args.output, "w", encoding="utf-8") as f:
                json.dump(res, f, indent=4)
            print(f"Saved JSON result to {args.output}")

    except Exception as e:
        logger.error(f"Inference error: {e}", exc_info=True)
        sys.exit(1)


if __name__ == "__main__":
    main()
